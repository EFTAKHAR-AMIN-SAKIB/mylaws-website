import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

function sha256(text) {
  return crypto.createHash('sha256').update(text || '', 'utf8').digest('hex');
}

function computeHash(p) {
  const payload = [
    p.id,
    p.actId,
    p.sectionNumber,
    p.originalText,
    p.originalLanguage,
    p.plainExplanation?.bn,
    p.plainExplanation?.en,
    p.caution?.bn,
    p.caution?.en,
    p.sourceUrl,
    p.effectiveDate,
    p.legalStatus,
  ].join('|');
  return sha256(payload);
}

const workspaceDir = 'E:/vibe coding/POIDH/MyLaws Website';

// 1. Load Acts
const actsPath = path.join(workspaceDir, 'src/data/corpus/acts.json');
const acts = JSON.parse(fs.readFileSync(actsPath, 'utf8'));
const actIds = new Set(acts.map((a) => a.id));

// 2. Load Existing Provisions
const provisionsPath = path.join(workspaceDir, 'src/data/corpus/provisions.json');
const existingProvisions = JSON.parse(fs.readFileSync(provisionsPath, 'utf8'));

// 3. Load Batch 2 Parts
const part1 = JSON.parse(fs.readFileSync(path.join(workspaceDir, 'scripts/batch2_part1.json'), 'utf8'));
const part2 = JSON.parse(fs.readFileSync(path.join(workspaceDir, 'scripts/batch2_part2.json'), 'utf8'));
const part3 = JSON.parse(fs.readFileSync(path.join(workspaceDir, 'scripts/batch2_part3.json'), 'utf8'));
const allBatch2 = [...part1, ...part2, ...part3];

console.log(`Loaded ${existingProvisions.length} existing provisions.`);
console.log(`Loaded ${allBatch2.length} Batch 2 provisions (Part 1: ${part1.length}, Part 2: ${part2.length}, Part 3: ${part3.length}).`);

// 4. Merge Provisions (by ID)
const provMap = new Map();
for (const p of existingProvisions) {
  provMap.set(p.id, p);
}

let addedCount = 0;
let updatedCount = 0;

for (const p of allBatch2) {
  if (!p.id || !p.actId || !p.sectionNumber || !p.title?.bn || !p.title?.en || !p.originalText) {
    throw new Error(`Invalid provision object: ${JSON.stringify(p)}`);
  }
  if (!actIds.has(p.actId)) {
    throw new Error(`Provision ${p.id} references unknown actId: ${p.actId}`);
  }
  p.contentHash = computeHash(p);
  if (provMap.has(p.id)) {
    provMap.set(p.id, { ...provMap.get(p.id), ...p });
    updatedCount++;
  } else {
    provMap.set(p.id, p);
    addedCount++;
  }
}

const mergedProvisions = Array.from(provMap.values());
console.log(`Merge complete: ${addedCount} brand-new added, ${updatedCount} updated.`);
console.log(`Total provisions in corpus now: ${mergedProvisions.length}`);

// Category breakdown
const catCounts = {};
for (const p of mergedProvisions) {
  const c = (p.categories && p.categories[0]) || p.category || 'other';
  catCounts[c] = (catCounts[c] || 0) + 1;
}
console.log('Category Distribution across all 7 Categories:');
console.table(catCounts);

// Write back to provisions.json
fs.writeFileSync(provisionsPath, JSON.stringify(mergedProvisions, null, 2), 'utf8');

// 5. Compute Version Info
const corpusHash = sha256(JSON.stringify(mergedProvisions));
const versionData = {
  corpusVersion: '2026.10.30-batch2.1',
  publishedAt: new Date().toISOString(),
  contentHash: corpusHash,
  provisionCount: mergedProvisions.length,
  actsCount: acts.length,
  categories: ['work', 'threats', 'digital', 'consumer', 'land', 'family', 'rights']
};

const versionPath = path.join(workspaceDir, 'src/data/corpus/version.json');
fs.writeFileSync(versionPath, JSON.stringify(versionData, null, 2), 'utf8');
console.log(`Saved version info: ${versionData.corpusVersion}`);

// 6. Export Offline Pack
const packDir = path.join(workspaceDir, 'public/packs');
if (!fs.existsSync(packDir)) fs.mkdirSync(packDir, { recursive: true });
const packPath = path.join(packDir, 'mylaws_corpus_latest.json');
fs.writeFileSync(packPath, JSON.stringify({ version: versionData, acts, provisions: mergedProvisions }, null, 2), 'utf8');
console.log(`Exported offline pack: ${packPath}`);

// 7. Generate legal.generated.ts
const code = `/**
 * AUTOGENERATED FILE - DO NOT EDIT DIRECTLY.
 * Generated from src/data/corpus/provisions.json and acts.json by scripts/merge_and_compile_batch2.mjs
 * Published Corpus Version: ${versionData.corpusVersion}
 */

export type Lang = 'en' | 'bn';
export type Category = 'work' | 'threats' | 'digital' | 'consumer' | 'land' | 'family' | 'rights';
export type LegalStatus = 'active' | 'amended' | 'repealed' | 'transitional';
export type ReviewStatus = 'draft' | 'auto_checked' | 'human_reviewed';

export interface ActMetadata {
  id: string;
  name: { en: string; bn: string };
  actNumber: string;
  year: number;
  categories: Category[];
  officialUrl: string;
  legalStatus: LegalStatus;
  notes?: { en: string; bn: string };
}

export interface CanonicalProvision {
  id: string;
  actId: string;
  sectionNumber: string;
  categories: Category[];
  title: { en: string; bn: string };
  originalText: string;
  originalLanguage: Lang;
  plainExplanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  sourceUrl: string;
  retrievalDate: string;
  effectiveDate?: string;
  legalStatus: LegalStatus;
  reviewStatus: ReviewStatus;
  contentHash: string;
  keywords: string[];
  relatedProvisions?: string[];
}

export interface Provision {
  id: string;
  category: Category;
  act: { en: string; bn: string };
  section: string;
  title: { en: string; bn: string };
  quote: string;
  sourceLanguage: Lang;
  sourceUrl: string;
  checkedOn: string;
  explanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  keywords: string[];
  categories?: Category[];
  actId?: string;
  effectiveDate?: string;
  legalStatus?: LegalStatus;
  reviewStatus?: ReviewStatus;
  contentHash?: string;
}

export const CORPUS_VERSION = '${versionData.corpusVersion}';
export const CORPUS_HASH = '${versionData.contentHash}';
export const PUBLISHED_AT = '${versionData.publishedAt}';

export const canonicalActs: ActMetadata[] = ${JSON.stringify(acts, null, 2)};

export const canonicalProvisions: CanonicalProvision[] = ${JSON.stringify(mergedProvisions, null, 2)};

// Runtime view provision mapping
export const provisions: Provision[] = canonicalProvisions.map((cp) => {
  const act = canonicalActs.find((a) => a.id === cp.actId);
  const primaryCat = (cp.categories && cp.categories[0]) || 'rights';
  return {
    id: cp.id,
    category: primaryCat as Category,
    categories: cp.categories as Category[],
    actId: cp.actId,
    act: {
      en: act ? act.name.en : cp.actId,
      bn: act ? act.name.bn : cp.actId,
    },
    section: cp.sectionNumber,
    title: cp.title,
    quote: cp.originalText,
    sourceLanguage: cp.originalLanguage,
    sourceUrl: cp.sourceUrl,
    checkedOn: cp.retrievalDate,
    effectiveDate: cp.effectiveDate,
    legalStatus: cp.legalStatus,
    reviewStatus: cp.reviewStatus,
    contentHash: cp.contentHash,
    explanation: cp.plainExplanation,
    caution: cp.caution,
    keywords: cp.keywords || [],
  };
});
`;

const legalGeneratedPath = path.join(workspaceDir, 'src/data/legal.generated.ts');
fs.writeFileSync(legalGeneratedPath, code, 'utf8');
console.log(`Generated ${legalGeneratedPath} with ${mergedProvisions.length} provisions!`);
