import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

function sha256(text) {
  return crypto.createHash('sha256').update(text || '', 'utf8').digest('hex');
}

function computeHash(p) {
  const payload = [
    p.id,
    p.actId,
    p.sectionNumber,
    p.originalText,
    p.originalLanguage,
    p.plainExplanation?.bn,
    p.plainExplanation?.en,
    p.caution?.bn,
    p.caution?.en,
    p.sourceUrl,
    p.effectiveDate,
    p.legalStatus,
  ].join('|');
  return sha256(payload);
}

const workspaceDir = process.cwd();
const actsPath = path.join(workspaceDir, 'src/data/corpus/acts.json');
const provisionsPath = path.join(workspaceDir, 'src/data/corpus/provisions.json');

const acts = JSON.parse(fs.readFileSync(actsPath, 'utf8'));
const provisions = JSON.parse(fs.readFileSync(provisionsPath, 'utf8'));

const actMap = new Map();
for (const a of acts) {
  actMap.set(a.id, a);
}

// 1. Recompute individual content hashes
for (const p of provisions) {
  p.contentHash = computeHash(p);
  if (!p.categories || p.categories.length === 0) {
    p.categories = [p.category];
  }
}

// 2. Compute release hash
const sorted = [...provisions].sort((a, b) => a.id.localeCompare(b.id));
const releaseHash = sha256(sorted.map(p => `${p.id}:${p.contentHash}`).join('||'));

const CORPUS_VERSION = '2026.10.30-batch2.2';
const PUBLISHED_AT = new Date().toISOString();

// 3. Update provisions.json
fs.writeFileSync(provisionsPath, JSON.stringify(provisions, null, 2), 'utf8');

// 4. Update version.json
const versionInfo = {
  corpusVersion: CORPUS_VERSION,
  publishedAt: PUBLISHED_AT,
  contentHash: releaseHash,
  provisionCount: provisions.length,
  actsCount: acts.length
};
fs.writeFileSync(path.join(workspaceDir, 'src/data/corpus/version.json'), JSON.stringify(versionInfo, null, 2), 'utf8');

// 5. Generate legal.generated.ts
const code = `/**
 * AUTOGENERATED FILE - DO NOT EDIT DIRECTLY.
 * Generated from src/data/corpus/provisions.json and acts.json by scripts/compile_release.mjs
 * Published Corpus Version: ${CORPUS_VERSION}
 */

export type Lang = 'en' | 'bn';
export type Category = 'work' | 'threats' | 'digital' | 'consumer' | 'land' | 'family' | 'rights';
export type LegalStatus = 'active' | 'amended' | 'repealed' | 'transitional';
export type ReviewStatus = 'draft' | 'auto_checked' | 'human_reviewed';

export interface ActMetadata {
  id: string;
  name: { en: string; bn: string };
  actNumber: string;
  year: number;
  categories: Category[];
  officialUrl: string;
  legalStatus: LegalStatus;
  notes?: { en: string; bn: string };
}

export interface CanonicalProvision {
  id: string;
  actId: string;
  sectionNumber: string;
  categories: Category[];
  title: { en: string; bn: string };
  originalText: string;
  originalLanguage: Lang;
  plainExplanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  sourceUrl: string;
  retrievalDate: string;
  effectiveDate?: string;
  legalStatus: LegalStatus;
  reviewStatus: ReviewStatus;
  contentHash: string;
  keywords: string[];
  relatedProvisions?: string[];
}

export interface Provision {
  id: string;
  category: Category;
  act: { en: string; bn: string };
  section: string;
  title: { en: string; bn: string };
  quote: string;
  sourceLanguage: Lang;
  sourceUrl: string;
  checkedOn: string;
  explanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  keywords: string[];
  categories?: Category[];
  actId?: string;
  effectiveDate?: string;
  legalStatus?: LegalStatus;
  reviewStatus?: ReviewStatus;
  contentHash?: string;
  versionNote?: { en: string; bn: string };
}

export const CORPUS_VERSION = ${JSON.stringify(CORPUS_VERSION)};
export const CORPUS_HASH = ${JSON.stringify(releaseHash)};
export const PUBLISHED_AT = ${JSON.stringify(PUBLISHED_AT)};
export const CORPUS_PUBLISHED_AT = PUBLISHED_AT;

export const canonicalActs: ActMetadata[] = ${JSON.stringify(acts, null, 2)};

export const canonicalProvisions: CanonicalProvision[] = ${JSON.stringify(provisions, null, 2)};

export const provisions: Provision[] = canonicalProvisions.map((cp) => {
  const act = canonicalActs.find((a) => a.id === cp.actId);
  return {
    id: cp.id,
    category: cp.categories[0] || 'rights',
    categories: cp.categories,
    actId: cp.actId,
    act: {
      en: act?.name?.en || cp.actId,
      bn: act?.name?.bn || cp.actId,
    },
    section: cp.sectionNumber,
    title: cp.title,
    quote: cp.originalText,
    sourceLanguage: cp.originalLanguage,
    sourceUrl: cp.sourceUrl,
    checkedOn: cp.retrievalDate,
    effectiveDate: cp.effectiveDate,
    legalStatus: cp.legalStatus,
    reviewStatus: cp.reviewStatus,
    contentHash: cp.contentHash,
    explanation: cp.plainExplanation,
    caution: cp.caution,
    keywords: cp.keywords || [],
    versionNote: {
      en: \`Official text sourced from \${cp.sourceUrl}; status: \${cp.legalStatus}.\`,
      bn: \`সরকারি সূত্র: \${cp.sourceUrl}; স্থিতি: \${cp.legalStatus}.\`
    }
  };
});
`;

fs.writeFileSync(path.join(workspaceDir, 'src/data/legal.generated.ts'), code, 'utf8');

// 6. Generate public/packs/mylaws_corpus_latest.json
const offlinePack = {
  version: CORPUS_VERSION,
  publishedAt: PUBLISHED_AT,
  contentHash: releaseHash,
  provisionCount: provisions.length,
  actsCount: acts.length,
  acts,
  provisions: provisions.map((cp) => {
    const act = actMap.get(cp.actId);
    return {
      id: cp.id,
      category: cp.categories[0] || 'rights',
      categories: cp.categories,
      actId: cp.actId,
      act: {
        en: act?.name?.en || cp.actId,
        bn: act?.name?.bn || cp.actId,
      },
      section: cp.sectionNumber,
      title: cp.title,
      quote: cp.originalText,
      sourceLanguage: cp.originalLanguage,
      sourceUrl: cp.sourceUrl,
      checkedOn: cp.retrievalDate,
      effectiveDate: cp.effectiveDate,
      legalStatus: cp.legalStatus,
      reviewStatus: cp.reviewStatus,
      contentHash: cp.contentHash,
      explanation: cp.plainExplanation,
      caution: cp.caution,
      keywords: cp.keywords || [],
    };
  })
};

fs.writeFileSync(path.join(workspaceDir, 'public/packs/mylaws_corpus_latest.json'), JSON.stringify(offlinePack, null, 2), 'utf8');

console.log('Successfully compiled release!');
console.log(`Provisions: ${provisions.length}`);
console.log(`Acts: ${acts.length}`);
console.log(`Release Hash: ${releaseHash}`);
