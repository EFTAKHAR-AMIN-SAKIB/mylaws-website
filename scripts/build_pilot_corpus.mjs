import fs from 'fs';
import path from 'path';
import crypto from 'crypto';

const workspaceDir = 'E:/vibe coding/POIDH/MyLaws Website';

// 1. Load Acts Inventory
const acts = JSON.parse(fs.readFileSync(path.join(workspaceDir, 'src/data/corpus/acts.json'), 'utf-8'));
const actMap = new Map(acts.map((a) => [a.id, a]));

// 2. Load Deduplicated Provisions
const provisionsJsonPath = path.join(workspaceDir, 'src/data/corpus/provisions.json');
const canonicalProvisions = JSON.parse(fs.readFileSync(provisionsJsonPath, 'utf-8'));

function sha256(text) {
  return crypto.createHash('sha256').update(text || '', 'utf8').digest('hex');
}

// Ensure every item has a contentHash
for (const p of canonicalProvisions) {
  if (!p.contentHash) {
    p.contentHash = sha256(p.originalText);
  }
}

// Compute overall corpus hash
const corpusHash = sha256(JSON.stringify(canonicalProvisions));
const versionData = {
  corpusVersion: '2026.10.30-pilot.2',
  publishedAt: new Date().toISOString(),
  contentHash: corpusHash,
  provisionCount: canonicalProvisions.length,
  actsCount: acts.length,
  categories: ['work', 'threats', 'digital', 'consumer', 'land', 'family', 'rights']
};

const versionJsonPath = path.join(workspaceDir, 'src/data/corpus/version.json');
fs.writeFileSync(versionJsonPath, JSON.stringify(versionData, null, 2), 'utf-8');
console.log(`Saved version info: ${versionData.corpusVersion} (${canonicalProvisions.length} provisions)`);

// Export offline pack
const packDir = path.join(workspaceDir, 'public/packs');
if (!fs.existsSync(packDir)) fs.mkdirSync(packDir, { recursive: true });
const packPath = path.join(packDir, 'mylaws_corpus_latest.json');
fs.writeFileSync(packPath, JSON.stringify({ version: versionData, acts, provisions: canonicalProvisions }, null, 2), 'utf-8');
console.log(`Exported offline pack to ${packPath}`);

// Generate src/data/legal.generated.ts
const code = `/**
 * AUTOGENERATED FILE - DO NOT EDIT DIRECTLY.
 * Generated from src/data/corpus/provisions.json and acts.json by scripts/build_pilot_corpus.mjs
 * Published Corpus Version: ${versionData.corpusVersion}
 */

export type Lang = 'en' | 'bn';
export type Category = 'work' | 'threats' | 'digital' | 'consumer' | 'land' | 'family' | 'rights';
export type LegalStatus = 'active' | 'amended' | 'repealed' | 'transitional';
export type ReviewStatus = 'draft' | 'auto_checked' | 'human_reviewed';

export interface ActMetadata {
  id: string;
  name: { en: string; bn: string };
  actNumber: string;
  year: number;
  categories: Category[];
  officialUrl: string;
  legalStatus: LegalStatus;
  notes?: { en: string; bn: string };
}

export interface CanonicalProvision {
  id: string;
  actId: string;
  sectionNumber: string;
  categories: Category[];
  title: { en: string; bn: string };
  originalText: string;
  originalLanguage: Lang;
  plainExplanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  sourceUrl: string;
  retrievalDate: string;
  effectiveDate?: string;
  legalStatus: LegalStatus;
  reviewStatus: ReviewStatus;
  contentHash: string;
  keywords: string[];
  relatedProvisions?: string[];
}

export interface Provision {
  id: string;
  category: Category;
  act: { en: string; bn: string };
  section: string;
  title: { en: string; bn: string };
  quote: string;
  sourceLanguage: Lang;
  sourceUrl: string;
  checkedOn: string;
  versionNote: { en: string; bn: string };
  explanation: { en: string; bn: string };
  caution: { en: string; bn: string };
  keywords: string[];
  categories?: Category[];
  actId?: string;
  contentHash?: string;
  legalStatus?: LegalStatus;
  reviewStatus?: ReviewStatus;
}

export const CORPUS_VERSION = '${versionData.corpusVersion}';
export const CORPUS_PUBLISHED_AT = '${versionData.publishedAt}';
export const CORPUS_HASH = '${versionData.contentHash}';

export const acts: ActMetadata[] = ${JSON.stringify(acts, null, 2)};

export const canonicalProvisions: CanonicalProvision[] = ${JSON.stringify(canonicalProvisions, null, 2)};

const actMap = new Map<string, ActMetadata>(acts.map((a) => [a.id, a]));

export const provisions: Provision[] = canonicalProvisions.map((cp) => {
  const act = actMap.get(cp.actId);
  return {
    id: cp.id,
    category: cp.categories[0] || 'rights',
    categories: cp.categories,
    actId: cp.actId,
    act: {
      en: act?.name.en || cp.actId,
      bn: act?.name.bn || cp.actId,
    },
    section: cp.sectionNumber,
    title: cp.title,
    quote: cp.originalText,
    sourceLanguage: cp.originalLanguage,
    sourceUrl: cp.sourceUrl,
    checkedOn: cp.retrievalDate,
    versionNote: { en: '', bn: '' },
    explanation: cp.plainExplanation,
    caution: cp.caution,
    keywords: cp.keywords,
    contentHash: cp.contentHash,
    legalStatus: cp.legalStatus,
    reviewStatus: cp.reviewStatus,
  };
});
`;

const generatedTsPath = path.join(workspaceDir, 'src/data/legal.generated.ts');
fs.writeFileSync(generatedTsPath, code, 'utf-8');
console.log(`Generated ${generatedTsPath} with ${canonicalProvisions.length} provisions!`);
